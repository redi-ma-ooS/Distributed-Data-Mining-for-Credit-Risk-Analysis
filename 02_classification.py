def build_random_param_maps_gbt(gbt, n_samples=12, seed=42):
    random.seed(seed)

    param_space = {
        "maxDepth": [3, 5, 7, 9],
        "maxIter": [20, 40, 60, 80],
        "stepSize": [0.05, 0.1, 0.2],
        "subsamplingRate": [0.6, 0.8, 1.0]
    }

    all_combos = list(itertools.product(
        param_space["maxDepth"],
        param_space["maxIter"],
        param_space["stepSize"],
        param_space["subsamplingRate"]
    ))

    sampled = random.sample(all_combos, k=min(n_samples, len(all_combos)))

    param_maps = []

    for maxDepth, maxIter, stepSize, subsamplingRate in sampled:
        pm = {
            gbt.maxDepth: maxDepth,
            gbt.maxIter: maxIter,
            gbt.stepSize: stepSize,
            gbt.subsamplingRate: subsamplingRate
        }
        param_maps.append(pm)

    return param_maps

def tune_and_train_gbt(
    train_tune_input_df,
    train_full_input_df,
    n_random=12,
    seed=42,
    threshold_candidates=[0.20, 0.25, 0.30, 0.35, 0.40, 0.50]
):
    from sklearn.metrics import precision_score, recall_score, f1_score

    gbt = GBTClassifier(
        labelCol="label",
        featuresCol="selected_features",
        seed=seed
    )

    param_maps = build_random_param_maps_gbt(gbt, n_samples=n_random, seed=seed)

    evaluator = BinaryClassificationEvaluator(
        labelCol="label",
        rawPredictionCol="rawPrediction",
        metricName="areaUnderROC"
    )

    cv = CrossValidator(
        estimator=gbt,
        estimatorParamMaps=param_maps,
        evaluator=evaluator,
        numFolds=3,
        seed=seed,
        parallelism=2
    )

    cv_model = cv.fit(train_tune_input_df)
    best_gbt_model = cv_model.bestModel

    best_params = {
        "maxDepth": best_gbt_model.getMaxDepth(),
        "maxIter": best_gbt_model.getMaxIter(),
        "stepSize": best_gbt_model.getStepSize(),
        "subsamplingRate": best_gbt_model.getSubsamplingRate()
    }


    tune_preds = best_gbt_model.transform(train_tune_input_df).select("label", "probability")
    tune_pd = tune_preds.toPandas()

    y_true = tune_pd["label"].astype(int).values
    y_score = tune_pd["probability"].apply(lambda v: float(v[1])).values

    threshold_results = []

    for thr in threshold_candidates:
        y_pred = (y_score >= thr).astype(int)

        precision = precision_score(y_true, y_pred, zero_division=0)
        recall = recall_score(y_true, y_pred, zero_division=0)
        f1 = f1_score(y_true, y_pred, zero_division=0)

        threshold_results.append({
            "threshold": thr,
            "precision_default": precision,
            "recall_default": recall,
            "f1_default": f1
        })

    threshold_df = pd.DataFrame(threshold_results).sort_values(
        ["f1_default", "recall_default"],
        ascending=False
    ).reset_index(drop=True)

    best_threshold = float(threshold_df.loc[0, "threshold"])

    print("\nBest parameters:")
    print({
        "maxDepth": best_params["maxDepth"],
        "maxIter": best_params["maxIter"],
        "stepSize": best_params["stepSize"],
        "subsamplingRate": best_params["subsamplingRate"],
        "threshold": best_threshold
    })


    final_gbt = GBTClassifier(
        labelCol="label",
        featuresCol="selected_features",
        maxDepth=best_params["maxDepth"],
        maxIter=best_params["maxIter"],
        stepSize=best_params["stepSize"],
        subsamplingRate=best_params["subsamplingRate"],
        seed=seed
    )

    final_model = final_gbt.fit(train_full_input_df)

    return final_model, best_params, best_threshold, threshold_df

