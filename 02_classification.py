def build_random_param_maps(lr, n_samples=12, seed=42):
    random.seed(seed)

    param_space = {
        "regParam": [0.0, 0.001, 0.01, 0.05, 0.1],
        "elasticNetParam": [0.0, 0.25, 0.5, 0.75, 1.0],
        "maxIter": [30, 50, 80, 120],
        "threshold": [0.35, 0.4, 0.45, 0.5]
    }

    all_combos = list(itertools.product(
        param_space["regParam"],
        param_space["elasticNetParam"],
        param_space["maxIter"],
        param_space["threshold"]
    ))

    sampled = random.sample(all_combos, k=min(n_samples, len(all_combos)))

    param_maps = []
    for regParam, elasticNetParam, maxIter, threshold in sampled:
        pm = {
            lr.regParam: regParam,
            lr.elasticNetParam: elasticNetParam,
            lr.maxIter: maxIter,
            lr.threshold: threshold
        }
        param_maps.append(pm)

    return param_maps

def tune_and_train_lr(train_tune_input_df, train_full_input_df, use_weights=False, n_random=12, seed=42):
    if use_weights:
        lr = LogisticRegression(
            labelCol="label",
            featuresCol="selected_features",
            weightCol="classWeight"
        )
    else:
        lr = LogisticRegression(
            labelCol="label",
            featuresCol="selected_features"
        )

    param_maps = build_random_param_maps(lr, n_samples=n_random, seed=seed)

    evaluator = BinaryClassificationEvaluator(
        labelCol="label",
        rawPredictionCol="rawPrediction",
        metricName="areaUnderROC"
    )

    cv = CrossValidator(
        estimator=lr,
        estimatorParamMaps=param_maps,
        evaluator=evaluator,
        numFolds=3,
        seed=seed,
        parallelism=2
    )

    cv_model = cv.fit(train_tune_input_df)
    best_lr_model = cv_model.bestModel

    best_params = {
        "regParam": best_lr_model.getRegParam(),
        "elasticNetParam": best_lr_model.getElasticNetParam(),
        "maxIter": best_lr_model.getMaxIter(),
        "threshold": best_lr_model.getThreshold()
    }

    print("\nBest parameters:")
    print(best_params)

    if use_weights:
        final_lr = LogisticRegression(
            labelCol="label",
            featuresCol="selected_features",
            weightCol="classWeight",
            regParam=best_params["regParam"],
            elasticNetParam=best_params["elasticNetParam"],
            maxIter=best_params["maxIter"],
            threshold=best_params["threshold"]
        )
    else:
        final_lr = LogisticRegression(
            labelCol="label",
            featuresCol="selected_features",
            regParam=best_params["regParam"],
            elasticNetParam=best_params["elasticNetParam"],
            maxIter=best_params["maxIter"],
            threshold=best_params["threshold"]
        )

    final_model = final_lr.fit(train_full_input_df)

    return final_model, best_params

def evaluate_lr_model(model, test_input_df, title_prefix="Logistic Regression"):
    preds = model.transform(test_input_df).select("label", "prediction", "probability", "rawPrediction")

    evaluator_roc = BinaryClassificationEvaluator(
        labelCol="label",
        rawPredictionCol="rawPrediction",
        metricName="areaUnderROC"
    )

    evaluator_pr = BinaryClassificationEvaluator(
        labelCol="label",
        rawPredictionCol="rawPrediction",
        metricName="areaUnderPR"
    )

    auc_roc = evaluator_roc.evaluate(preds)
    auc_pr = evaluator_pr.evaluate(preds)

    pred_pd = preds.toPandas()

    y_true = pred_pd["label"].astype(int).values
    y_pred = pred_pd["prediction"].astype(int).values
    y_score = pred_pd["probability"].apply(lambda v: float(v[1])).values

    print(f"\n{title_prefix} - ROC-AUC: {auc_roc:.4f}")
    print(f"{title_prefix} - PR-AUC:  {auc_pr:.4f}")

    report = classification_report(
        y_true,
        y_pred,
        target_names=["non-default (0)", "default (1)"],
        digits=4,
        zero_division=0
    )

    print(f"\n{title_prefix} - Classification Report:\n")
    print(report)


    fpr, tpr, _ = roc_curve(y_true, y_score)
    roc_auc = auc(fpr, tpr)

    plt.figure(figsize=(4, 3))
    plt.plot(fpr, tpr, label=f"AUC = {roc_auc:.3f}")
    plt.plot([0, 1], [0, 1], linestyle="--")
    plt.xlabel("False Positive Rate")
    plt.ylabel("True Positive Rate")
    plt.title(f"{title_prefix} ROC Curve")
    plt.legend(loc="lower right")
    plt.tight_layout()
    plt.show()

    cm = confusion_matrix(y_true, y_pred)

    fig, ax = plt.subplots(figsize=(4, 3))
    disp = ConfusionMatrixDisplay(
        confusion_matrix=cm,
        display_labels=["Pred 0", "Pred 1"]
    )
    disp.plot(cmap="Blues", ax=ax, colorbar=False)
    ax.set_title(f"{title_prefix} Confusion Matrix")
    ax.set_xlabel("Predicted Label")
    ax.set_ylabel("True Label")
    plt.tight_layout()
    plt.show()

    return {
        "auc_roc": auc_roc,
        "auc_pr": auc_pr,
        "classification_report": report
    }

