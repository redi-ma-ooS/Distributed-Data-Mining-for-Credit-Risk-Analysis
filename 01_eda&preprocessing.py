def plot_default_rate_by_grade_from_multiclass(
    df: DataFrame,
    status_col: str = "loan_status",
    grade_col: str = "grade"
) -> None:

    df_bin = (
        df.withColumn(
            "loan_status_label",
            F.when(F.col(status_col).isin("Charged Off", "Default"), F.lit(1))
             .when(F.col(status_col) == "Fully Paid", F.lit(0))
             .otherwise(F.lit(None))
        )
        .filter(F.col("loan_status_label").isNotNull())
    )

    rows = (
        df_bin.groupBy(grade_col)
              .agg(F.avg("loan_status_label").alias("default_rate"))
              .orderBy(grade_col)
              .collect()
    )

    grades = [r[grade_col] for r in rows]
    rates = [r["default_rate"] for r in rows]

    plt.figure(figsize=(4, 3))
    plt.bar(grades, rates)
    plt.title("Default Rate by Grade")
    plt.xlabel("Grade")
    plt.ylabel("Default Rate")
    plt.ylim(0, 1)
    plt.tight_layout()
    plt.show()

