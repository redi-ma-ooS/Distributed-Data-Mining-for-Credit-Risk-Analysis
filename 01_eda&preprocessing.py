def clean_missingness_and_bounds(
    spark: SparkSession,
    df: DataFrame,
    missing_threshold: float = 0.85,
    imbalance_threshold: float = 0.995,
    protect_cols: tuple[str, ...] = ("label", "id"),
    show_top_missing: int = 20,
) -> tuple[DataFrame, dict]:
    n = df.count()

    null_counts = df.select(
        [F.sum(F.col(c).isNull().cast("int")).alias(c) for c in df.columns]
    ).collect()[0].asDict()

    missing_summary = (
        spark.createDataFrame(
            [(c, int(null_counts[c]), float(null_counts[c]) / n if n else 0.0) for c in df.columns],
            ["column", "null_count", "null_pct"],
        )
        .orderBy(F.desc("null_pct"))
    )

    if show_top_missing and show_top_missing > 0:
        missing_summary.show(show_top_missing, truncate=False)

    sparse_cols = (
        missing_summary.filter((F.col("null_pct") > missing_threshold) & (~F.col("column").isin(list(protect_cols))))
        .select("column")
        .rdd.flatMap(lambda x: x)
        .collect()
    )

    df2 = df.drop(*sparse_cols) if sparse_cols else df

    numeric_cols = [
        f.name for f in df2.schema.fields
        if isinstance(f.dataType, NumericType) and f.name not in protect_cols
    ]

    agg_exprs = []
    for c in numeric_cols:
        agg_exprs.append(F.min(c).alias(f"{c}__min"))
        agg_exprs.append(F.max(c).alias(f"{c}__max"))

    stats = df2.agg(*agg_exprs).collect()[0].asDict() if agg_exprs else {}
    constant_numeric = [c for c in numeric_cols if stats.get(f"{c}__min") == stats.get(f"{c}__max")]

    df3 = df2.drop(*constant_numeric) if constant_numeric else df2

    string_cols = [
        f.name for f in df3.schema.fields
        if isinstance(f.dataType, StringType) and f.name not in protect_cols
    ]

    near_constant_string = []
    for c in string_cols:
        total_non_null = df3.where(F.col(c).isNotNull()).count()
        if total_non_null == 0:
            continue

        top = (
            df3.where(F.col(c).isNotNull())
               .groupBy(c).count()
               .orderBy(F.desc("count"))
               .limit(1)
               .collect()
        )
        if not top:
            continue

        if (top[0]["count"] / total_non_null) > imbalance_threshold:
            near_constant_string.append(c)

    df4 = df3.drop(*near_constant_string) if near_constant_string else df3

    df5 = (
        df4.withColumn(
            "loan_income_ratio",
            F.when((F.col("annual_inc") < 1000) | (F.col("loan_income_ratio") > 10), 10)
             .otherwise(F.col("loan_income_ratio")),
        )
        .withColumn(
            "installment_income_ratio",
            F.when((F.col("annual_inc") < 1000) | (F.col("installment_income_ratio") > 1), 1)
             .otherwise(F.col("installment_income_ratio")),
        )
        .withColumn("dti", F.when(F.col("dti") < 0, 0).otherwise(F.col("dti")))
        .withColumn(
            "revol_util",
            F.when(F.col("revol_util") < 0, 0)
             .when(F.col("revol_util") > 100, 100)
             .otherwise(F.col("revol_util")),
        )
        .withColumn(
            "credit_hist_months",
            F.when(F.col("credit_hist_months") < 0, None).otherwise(F.col("credit_hist_months")),
        )
        .withColumn(
            "fico_avg",
            F.when((F.col("fico_avg") < 300) | (F.col("fico_avg") > 850), None).otherwise(F.col("fico_avg")),
        )
    )

    for c in ["il_util", "bc_util", "all_util", "percent_bc_gt_75"]:
        if c in df5.columns:
            df5 = df5.withColumn(
                c,
                F.when(F.col(c) < 0, None)
                 .when(F.col(c) > 150, 150)
                 .otherwise(F.col(c)),
            )

    report = {
        "rows": n,
        "dropped_sparse": sparse_cols,
        "dropped_constant_numeric": constant_numeric,
        "dropped_near_constant_string": near_constant_string,
        "columns_before": len(df.columns),
        "columns_after": len(df5.columns),
    }

    return df5, report


