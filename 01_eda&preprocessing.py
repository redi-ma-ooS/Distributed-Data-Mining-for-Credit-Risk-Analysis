def _cols_with_prefix(df: DataFrame, prefixes: tuple[str, ...]) -> list[str]:
    cols = df.columns
    return [c for c in cols if any(c.startswith(p) for p in prefixes)]


def get_drop_columns(
    df: DataFrame,
    leakage_cols: list[str] | None = None,
    irrelevant_cols: list[str] | None = None,
    proxy_cols: list[str] | None = None,
    explicit_post_issue_extras: list[str] | None = None,
    post_issue_prefixes: tuple[str, ...] = ("hardship_", "settlement_", "debt_settlement_"),
) -> dict:
    if leakage_cols is None:
        leakage_cols = [
            "out_prncp", "out_prncp_inv",
            "total_pymnt", "total_pymnt_inv",
            "total_rec_prncp", "total_rec_int", "total_rec_late_fee",
            "recoveries", "collection_recovery_fee",
            "last_pymnt_d", "last_pymnt_amnt", "next_pymnt_d",
            "last_credit_pull_d",
            "last_fico_range_high", "last_fico_range_low",
        ]

    if irrelevant_cols is None:
        irrelevant_cols = ["member_id", "url", "desc", "title", "emp_title", "zip_code"]

    if proxy_cols is None:
        proxy_cols = ["sub_grade"]

    if explicit_post_issue_extras is None:
        explicit_post_issue_extras = [
            "deferral_term",
            "payment_plan_start_date",
            "orig_projected_additional_accrued_interest",
        ]

    existing = set(df.columns)
    dynamic_cols = _cols_with_prefix(df, post_issue_prefixes)

    drop_leakage = [c for c in leakage_cols if c in existing]
    drop_dynamic = [c for c in dynamic_cols if c in existing]
    drop_extras = [c for c in explicit_post_issue_extras if c in existing]
    drop_irrel = [c for c in irrelevant_cols if c in existing]
    drop_proxy = [c for c in proxy_cols if c in existing]

    all_drop = sorted(set(drop_leakage + drop_dynamic + drop_extras + drop_irrel + drop_proxy))

    return {
        "leakage": drop_leakage,
        "dynamic": drop_dynamic,
        "extras": drop_extras,
        "irrelevant": drop_irrel,
        "proxy": drop_proxy,
        "all": all_drop,
    }


def drop_columns(df: DataFrame, drop_report: dict) -> DataFrame:
    cols_to_drop = drop_report.get("all", [])
    return df.drop(*cols_to_drop) if cols_to_drop else df


