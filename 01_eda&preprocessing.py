"""**10. Missing Values Imputataion**"""

def train_fitted_imputation(
    train: DataFrame,
    test: DataFrame,
    classification_target: str = "label",
    regression_target: str = "int_rate",
    unknown_token: str = "Unknown",
) -> tuple[DataFrame, DataFrame]:
    numeric_cols_all = [
        f.name for f in train.schema.fields
        if isinstance(f.dataType, NumericType)
    ]
    cat_cols_all = [
        f.name for f in train.schema.fields
        if isinstance(f.dataType, StringType)
    ]

    numeric_feature_cols = [
        c for c in numeric_cols_all
        if c not in [classification_target, regression_target]
    ]

    train_null_counts = train.select(
        [F.sum(F.col(c).isNull().cast("int")).alias(c) for c in train.columns]
    ).collect()[0].asDict()

    numeric_missing = [c for c in numeric_feature_cols if train_null_counts.get(c, 0) > 0]
    cat_missing = [c for c in cat_cols_all if train_null_counts.get(c, 0) > 0]

    mths_since_missing = [c for c in numeric_missing if c.startswith("mths_since_")]
    continuous_missing = [c for c in numeric_missing if c not in mths_since_missing]

    medians = {}
    if continuous_missing:
        medians = train.select(
            [F.expr(f"percentile_approx({c}, 0.5)").alias(c) for c in continuous_missing]
        ).collect()[0].asDict()

    mths_fill = {}
    if mths_since_missing:
        max_vals = train.select([F.max(F.col(c)).alias(c) for c in mths_since_missing]).collect()[0].asDict()
        mths_fill = {
            c: float(max_vals[c]) + 1.0
            for c in mths_since_missing
            if max_vals.get(c) is not None
        }

    def apply(df: DataFrame) -> DataFrame:
        out = df

        for c, mv in medians.items():
            if mv is not None and c in out.columns:
                out = out.withColumn(c, F.when(F.col(c).isNull(), F.lit(mv)).otherwise(F.col(c)))

        for c, fv in mths_fill.items():
            if fv is not None and c in out.columns:
                out = out.withColumn(c, F.when(F.col(c).isNull(), F.lit(fv)).otherwise(F.col(c)))

        for c in cat_missing:
            if c in out.columns:
                out = out.withColumn(c, F.when(F.col(c).isNull(), F.lit(unknown_token)).otherwise(F.col(c)))

        return out

    return apply(train), apply(test)


