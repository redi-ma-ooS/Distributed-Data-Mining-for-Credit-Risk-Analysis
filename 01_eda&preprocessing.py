"""**8. Correlation Analysis & Redundant Feature Identification**"""

def correlation_analysis(
    spark,
    df: DataFrame,
    target_col: str = "int_rate",
    label_col: str = "label",
    top_n: int = 10,
    threshold: float = 0.90,
) -> None:

    numeric_cols = [
        f.name for f in df.schema.fields
        if isinstance(f.dataType, NumericType)
        and f.name not in [target_col, label_col]
    ]

    df_corr = df.select(numeric_cols).dropna()

    assembler = VectorAssembler(
        inputCols=numeric_cols,
        outputCol="features",
        handleInvalid="skip",
    )

    df_vec = assembler.transform(df_corr).select("features")
    corr_row = Correlation.corr(df_vec, "features", "pearson").head()
    corr_np = np.array(corr_row[0].toArray())
    corr_df = pd.DataFrame(corr_np, index=numeric_cols, columns=numeric_cols)

    figsize = (max(10, len(numeric_cols) * 0.35),
               max(8, len(numeric_cols) * 0.35))

    plt.figure(figsize=figsize)
    plt.imshow(corr_np)
    plt.title("Pearson Correlation Matrix")
    plt.xticks(range(len(numeric_cols)), numeric_cols, rotation=90, fontsize=6)
    plt.yticks(range(len(numeric_cols)), numeric_cols, fontsize=6)
    plt.colorbar()
    plt.tight_layout()
    plt.show()

    avg_abs = np.mean(np.abs(corr_np - np.eye(corr_np.shape[0])), axis=1)
    top_idx = np.argsort(-avg_abs)[:top_n]
    top_cols = [numeric_cols[i] for i in top_idx]
    sub = corr_df.loc[top_cols, top_cols].values

    plt.figure(figsize=(7, 6))
    plt.imshow(sub)

    for i in range(top_n):
        for j in range(top_n):
            plt.text(j, i, f"{sub[i, j]:.2f}", ha="center", va="center", color="black", fontsize=7)

    plt.title(f"Pearson Correlation Matrix (Top {top_n})")
    plt.xticks(range(top_n), top_cols, rotation=90, fontsize=7)
    plt.yticks(range(top_n), top_cols, fontsize=7)
    plt.colorbar()
    plt.tight_layout()
    plt.show()

    pairs = []
    for i in range(len(numeric_cols)):
        for j in range(i + 1, len(numeric_cols)):
            r = float(corr_np[i, j])
            if abs(r) >= threshold:
                pairs.append((numeric_cols[i], numeric_cols[j], r))

    pairs_sorted = sorted(pairs, key=lambda x: abs(x[2]), reverse=True)

    print(f"Highly correlated feature pairs (|r| >= {threshold}):", len(pairs_sorted))
    for a, b, r in pairs_sorted[:30]:
        print(f"{a:30s}  vs  {b:30s}  corr={r:.4f}")

    print("Done!")


# call
correlation_analysis(spark, df_clean)

