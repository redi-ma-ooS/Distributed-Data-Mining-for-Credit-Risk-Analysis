def prepare_classification_df(
    df: DataFrame,
    status_map: dict,
    target_col: str = "loan_status",
    required_cols: list[str] = None,
) -> DataFrame:

    if required_cols is None:
        required_cols = [target_col, "int_rate"]

    final_statuses = list(status_map.keys())
    map_expr = F.create_map([F.lit(x) for kv in status_map.items() for x in kv])

    df_cls = (
        df.na.drop(subset=required_cols)
          .filter(F.col(target_col).isin(final_statuses))
          .withColumn("label", map_expr[F.col(target_col)])
          .drop(target_col)
    )

    print("Rows after outcome filtering:", df_cls.count())
    df_cls.groupBy("label").count().show()

    default_rate = df_cls.select(
        (F.mean("label") * 100).alias("default_rate_pct")
    ).first()["default_rate_pct"]

    print("Default rate (%):", default_rate)

    return df_cls


