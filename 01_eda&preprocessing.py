def engineer_features(df: DataFrame) -> DataFrame:
    df2 = (
        df.withColumn("issue_date", F.to_date(F.col("issue_d"), "MMM-yyyy"))
          .withColumn("earliest_cr_line_date", F.to_date(F.col("earliest_cr_line"), "MMM-yyyy"))
          .withColumn("sec_app_earliest_cr_line_date", F.to_date(F.col("sec_app_earliest_cr_line"), "MMM-yyyy"))
          .withColumn("term_months", F.regexp_extract(F.col("term"), r"(\d+)", 1).cast("int"))
          .withColumn(
              "emp_length_years",
              F.when(F.col("emp_length").isNull(), F.lit(None).cast("int"))
               .when(F.col("emp_length") == "10+ years", F.lit(10))
               .when(F.col("emp_length") == "< 1 year", F.lit(0))
               .otherwise(F.regexp_extract(F.col("emp_length"), r"(\d+)", 1).cast("int"))
          )
          .withColumn(
              "credit_hist_months",
              F.months_between(F.col("issue_date"), F.col("earliest_cr_line_date"))
          )
          .withColumn(
              "fico_avg",
              (F.col("fico_range_low") + F.col("fico_range_high")) / 2
          )
          .withColumn(
              "loan_income_ratio",
              F.when(F.col("annual_inc") > 0, F.col("loan_amnt") / F.col("annual_inc")).otherwise(F.lit(None))
          )
          .withColumn(
              "installment_income_ratio",
              F.when(F.col("annual_inc") > 0, F.col("installment") / F.col("annual_inc")).otherwise(F.lit(None))
          )
          .drop(
              "issue_d",
              "earliest_cr_line",
              "sec_app_earliest_cr_line",
              "earliest_cr_line_date",
              "sec_app_earliest_cr_line_date",
              "term",
              "emp_length",
              "fico_range_low",
              "fico_range_high",
          )
    )
    return df2


