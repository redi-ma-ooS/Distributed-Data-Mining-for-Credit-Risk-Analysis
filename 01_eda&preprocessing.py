"""**9. Time-Aware Train/Test Split**"""

def chronological_train_test_split(
    df: DataFrame,
    date_col: str = "issue_date",
    train_frac: float = 0.8,
    drop_cols_after_split: tuple[str, ...] = ("issue_date", "id"),
) -> tuple[DataFrame, DataFrame]:

    if date_col not in df.columns:
        raise ValueError(f"{date_col} column missing")

    w = Window.orderBy(F.col(date_col))
    df_ordered = df.withColumn("row_num", F.row_number().over(w))

    total = df_ordered.count()
    split_index = int(total * train_frac)

    train = df_ordered.filter(F.col("row_num") <= split_index).drop("row_num")
    test = df_ordered.filter(F.col("row_num") > split_index).drop("row_num")

    cols_to_remove = [c for c in drop_cols_after_split if c in train.columns]
    if cols_to_remove:
        train = train.drop(*cols_to_remove)
        test = test.drop(*cols_to_remove)

    return train, test


