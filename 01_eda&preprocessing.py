def plot_category_distribution(
    df,
    column,
    top_n=None,
    figsize=(8, 4.5),
    wrap_width=26,
    sort_desc=True
):
    agg = df.groupBy(column).count()
    agg = agg.orderBy(F.desc("count")) if sort_desc else agg.orderBy("count")

    pdf = agg.toPandas()

    if top_n is not None and len(pdf) > top_n:
        top = pdf.iloc[:top_n].copy()
        other_count = pdf.iloc[top_n:]["count"].sum()
        other = pd.DataFrame({column: ["Other"], "count": [other_count]})
        pdf = pd.concat([top, other], ignore_index=True)

    pdf[column] = pdf[column].astype(str).apply(
        lambda s: "\n".join(textwrap.wrap(s, width=wrap_width))
    )

    plt.figure(figsize=figsize)
    plt.barh(pdf[column][::-1], pdf["count"][::-1])

    plt.title(f"Distribution of {column}")
    plt.xlabel("Count")
    plt.ylabel(column)

    for i, cnt in enumerate(pdf["count"][::-1].values):
        plt.text(cnt, i, f"  {cnt:,}", va="center", fontsize=9)

    plt.tight_layout()
    plt.show()

